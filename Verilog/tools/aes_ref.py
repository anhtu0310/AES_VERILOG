#!/usr/bin/env python3
"""Pure-Python AES-128 reference model and test-vector generator.

No third-party packages: the S-box is computed from its definition
(multiplicative inverse in GF(2^8) followed by the affine transform), so the
model does not share a hand-typed table with the RTL.

  aes_ref.py selftest                     check against FIPS-197 / SP 800-38A
  aes_ref.py vectors -n N --seed S -o F   write N random vectors: "key pt ct"
  aes_ref.py sbox-vh -o F                 write the S-box case table for the RTL
  aes_ref.py c-header -n N --seed S -o F  C arrays (uint32_t words, little-endian)
"""
import argparse
import random
import sys


def _gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p


def _make_sbox():
    sbox = []
    for x in range(256):
        inv = 0
        if x:
            inv = next(y for y in range(1, 256) if _gmul(x, y) == 1)
        s = inv
        for i in range(1, 5):
            s ^= ((inv << i) | (inv >> (8 - i))) & 0xFF
        sbox.append(s ^ 0x63)
    return sbox


SBOX = _make_sbox()


def expand_key(key):
    """Returns the 11 round keys (16 bytes each) of a 16-byte key."""
    w = [list(key[4 * i:4 * i + 4]) for i in range(4)]
    rcon = 1
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = [SBOX[b] for b in t[1:] + t[:1]]
            t[0] ^= rcon
            rcon = _gmul(rcon, 2)
        w.append([a ^ b for a, b in zip(w[i - 4], t)])
    return [bytes(sum(w[4 * r:4 * r + 4], [])) for r in range(11)]


def encrypt_block(key, block):
    rk = expand_key(key)
    s = [a ^ b for a, b in zip(block, rk[0])]
    for r in range(1, 11):
        s = [SBOX[b] for b in s]
        # state byte i is row i % 4, column i // 4
        s = [s[(i + 4 * (i % 4)) % 16] for i in range(16)]
        if r != 10:
            m = []
            for c in range(4):
                a = s[4 * c:4 * c + 4]
                for i in range(4):
                    m.append(_gmul(a[i], 2) ^ _gmul(a[(i + 1) % 4], 3)
                             ^ a[(i + 2) % 4] ^ a[(i + 3) % 4])
            s = m
        s = [a ^ b for a, b in zip(s, rk[r])]
    return bytes(s)


# FIPS-197 Appendix B and C.1, NIST SP 800-38A F.1.1 (ECB-AES128)
KNOWN = [
    ("2b7e151628aed2a6abf7158809cf4f3c", "3243f6a8885a308d313198a2e0370734", "3925841d02dc09fbdc118597196a0b32"),
    ("000102030405060708090a0b0c0d0e0f", "00112233445566778899aabbccddeeff", "69c4e0d86a7b0430d8cdb78070b4c55a"),
    ("2b7e151628aed2a6abf7158809cf4f3c", "6bc1bee22e409f96e93d7e117393172a", "3ad77bb40d7a3660a89ecaf32466ef97"),
    ("2b7e151628aed2a6abf7158809cf4f3c", "ae2d8a571e03ac9c9eb76fac45af8e51", "f5d3d58503b9699de785895a96fdbaaf"),
    ("2b7e151628aed2a6abf7158809cf4f3c", "30c81c46a35ce411e5fbc1191a0a52ef", "43b1cd7f598ece23881b00e3ed030688"),
    ("2b7e151628aed2a6abf7158809cf4f3c", "f69f2445df4f9b17ad2b417be66c3710", "7b0c785e27e8ad3f8223207104725dd4"),
]


def selftest():
    bad = 0
    for k, p, c in KNOWN:
        got = encrypt_block(bytes.fromhex(k), bytes.fromhex(p)).hex()
        if got != c:
            print(f"FAIL key={k} pt={p}: got {got} expected {c}")
            bad += 1
    rk = expand_key(bytes.fromhex(KNOWN[0][0]))
    if rk[10].hex() != "d014f9a8c9ee2589e13f0cc8b6630ca6":     # FIPS-197 A.1
        print("FAIL key expansion")
        bad += 1
    print("selftest", "FAILED" if bad else "passed", f"({len(KNOWN) + 1} checks)")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["selftest", "vectors", "sbox-vh", "c-header"])
    ap.add_argument("-n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("-o", "--out", default="-")
    a = ap.parse_args()

    if a.cmd == "selftest":
        return selftest()

    out = sys.stdout if a.out == "-" else open(a.out, "w")
    rng = random.Random(a.seed)
    rows = list(KNOWN)
    for _ in range(a.n):
        k = bytes(rng.getrandbits(8) for _ in range(16))
        p = bytes(rng.getrandbits(8) for _ in range(16))
        rows.append((k.hex(), p.hex(), encrypt_block(k, p).hex()))

    if a.cmd == "vectors":
        for k, p, c in rows:
            out.write(f"{k} {p} {c}\n")
    elif a.cmd == "c-header":
        def words(h):
            b = bytes.fromhex(h)
            return ", ".join(f"0x{int.from_bytes(b[i:i + 4], 'little'):08x}" for i in range(0, 16, 4))
        out.write(f"/* Generated by tools/aes_ref.py c-header -n {a.n} --seed {a.seed}; do not edit.\n"
                  " * FIPS-197 B, C.1 and SP 800-38A F.1.1 vectors, then random ones. Each\n"
                  " * block is four little-endian words (byte 0 in bits 7:0 of word 0). */\n")
        out.write(f"#define AES_NVEC {len(rows)}\n")
        for name, col in (("key", 0), ("pt", 1), ("ct", 2)):
            out.write(f"static const uint32_t aes_vec_{name}[AES_NVEC][4] = {{\n")
            for r in rows:
                out.write(f"    {{ {words(r[col])} }},\n")
            out.write("};\n")
    else:
        out.write("// Generated by tools/aes_ref.py sbox-vh; do not edit.\n")
        out.write("// AES S-box (FIPS-197 Figure 7) as a 256-entry case table. Synthesis\n")
        out.write("// maps it to LUTs (8 x LUT6 + F7/F8 muxes per output bit on 7-series).\n")
        out.write("function [7:0] aes_sbox;\n    input [7:0] x;\n    begin\n        case (x)\n")
        for i, s in enumerate(SBOX):
            out.write(f"            8'h{i:02x}: aes_sbox = 8'h{s:02x};\n")
        out.write("            default: aes_sbox = 8'h00;\n")
        out.write("        endcase\n    end\nendfunction\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
